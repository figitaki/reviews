defmodule ReviewsWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :reviews

  # Phoenix inserts socket dispatch ahead of ordinary endpoint plugs.
  # Wrap the generated pipeline so handshakes also pay the cheap IP budget.
  def call(conn, opts) do
    case ReviewsWeb.Plugs.RequestBudget.call(conn, []) do
      %{halted: true} = conn -> conn
      conn -> super(conn, opts)
    end
  end

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  @session_options [
    store: :cookie,
    key: "_reviews_key",
    signing_salt: "Dwicoafg",
    same_site: "Lax"
  ]

  socket "/live", Phoenix.LiveView.Socket,
    websocket: [connect_info: [session: @session_options]],
    longpoll: [connect_info: [session: @session_options]]

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :reviews,
    gzip: not code_reloading?,
    only: ReviewsWeb.static_paths(),
    # `~p` links the digested root files `mix phx.digest` writes, such as
    # /favicon-<hash>.ico and /site-<hash>.webmanifest, which `only:` misses.
    only_matching: ~w(favicon- site-),
    raise_on_missing_only: code_reloading?

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :reviews
  end

  # Aggregate authentication runs before request logging, telemetry, redirects and body parsing.
  plug ReviewsWeb.Plugs.AggregateExport

  plug Phoenix.LiveDashboard.RequestLogger,
    param_key: "request_logger",
    cookie_key: "request_logger"

  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  # Redirect legacy hostnames (reviews-dev.fly.dev) to the canonical PHX_HOST.
  plug ReviewsWeb.Plugs.CanonicalHost

  # Authenticates API writes, then parses bodies with per-route limits. See
  # docs/ABUSE_PROTECTION.md.
  plug ReviewsWeb.Plugs.BodyBudget

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options
  plug ReviewsWeb.Router
end
